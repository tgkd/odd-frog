import AppKit
import Foundation

public struct ClipboardPasteboard: Sendable {
    public enum AccessRequest: Sendable {
        case noText
        case read
    }

    public let name: NSPasteboard.Name
    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    public init(name: NSPasteboard.Name) {
        self.name = name
    }

    @MainActor public func state() -> (changeCount: Int, behavior: NSPasteboard.AccessBehavior) {
        let pasteboard = NSPasteboard(name: name)
        return (pasteboard.changeCount, pasteboard.accessBehavior)
    }

    @MainActor public func capture() -> ClipboardCapture? {
        let pasteboard = NSPasteboard(name: name)
        guard let item = pasteboard.pasteboardItems?.first else {
            return nil
        }
        let types = item.types
        if types.contains(Self.concealed) || types.contains(Self.transient) || types.contains(Self.autoGenerated) {
            return nil
        }
        if types.contains(.fileURL) {
            return nil
        }
        if let text = item.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if text.utf8.count > ClipboardLimits.maxTextBytes {
                return nil
            }
            return .text(text)
        }
        if let data = item.data(forType: .png) {
            return .image(data: data, type: .png)
        }
        if let data = item.data(forType: .tiff) {
            return .image(data: data, type: .tiff)
        }
        return nil
    }

    @MainActor public func requestAccess() -> AccessRequest {
        let pasteboard = NSPasteboard(name: name)
        guard let item = pasteboard.pasteboardItems?.first else {
            return .noText
        }
        let types = item.types
        if types.contains(Self.concealed) || types.contains(Self.transient) || types.contains(Self.autoGenerated) {
            return .noText
        }
        guard types.contains(.string) else {
            return .noText
        }
        _ = item.string(forType: .string)
        return .read
    }
}
